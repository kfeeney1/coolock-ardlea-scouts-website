import { calendarDays } from "../src/services/groupCalendar";
import { expect, test } from "@playwright/test";
import { loginAsLeader } from "./support/authentication-helpers";
import { seedCalendarSources } from "./support/calendar-source-fixtures";
import { FirestoreListenTargets } from "./support/firestore-listen-targets";
const password = process.env.E2E_TEST_USER_PASSWORD;
test("canonical monthly sources stay clickable, refresh live, filter and restore record context", async ({page}, testInfo) => {
  test.skip(!password, "Configure canonical E2E credentials.");
  const fixture = await seedCalendarSources();
  const targets = new FirestoreListenTargets("events");
  let track = true;
  page.on("request", request => {if (track && page.url().includes("/calendar?") && request.url().includes("/Listen/channel")) targets.record(request.postData());});
  try {
    await loginAsLeader(page, {email: process.env.E2E_SUPER_ADMIN_EMAIL || "superadmin@example.com", password: password!});
    await page.goto(`/calendar?month=${fixture.month}`);
    const grid = page.getByRole("table", {name: "Monthly group calendar"});
    const cell = grid.locator(`[data-calendar-date="${fixture.month}-22"]`);
    await expect(cell.getByRole("link", {name: /^Meeting: SW336 Pioneering/})).toBeVisible();
    await expect(cell.getByRole("link", {name: /^Event: SW336 Camp/})).toBeVisible();
    await expect(cell.getByRole("link", {name: /^Event: SW336 Second event/})).toBeVisible();
    await expect(grid.locator(`[data-calendar-date="${fixture.month}-23"]`).getByRole("link", {name: /^Event: SW336 Camp/})).toBeVisible();
    await expect(grid.locator(`[data-calendar-date="${fixture.month}-02"]`).getByRole("link", {name: /^Event: SW336 Spanning/})).toBeVisible();
    await expect(grid.getByRole("link", {name: /SW336 Outside month/})).toHaveCount(0);
    await expect(grid.locator(`[data-calendar-date="${fixture.month}-03"]`).getByRole("link", {name: /^Event: SW336 Spanning/})).toBeVisible();
    await expect(grid.locator(`[data-calendar-date="${fixture.month}-04"]`).getByRole("link", {name: /^Event: SW336 Spanning/})).toHaveCount(0);
    await page.screenshot({path: testInfo.outputPath("calendar-all-sources.png"), fullPage: true});
    const reads = targets.values(); expect(reads.length).toBeGreaterThan(0); expect(reads.length).toBeLessThanOrEqual(14);
    for (const target of reads) {const text = JSON.stringify(target.query.structuredQuery?.where); expect(text).toContain("startDate"); expect(text).toContain(calendarDays(fixture.month)[0]);}
    track = false;
    await cell.getByRole("link", {name: /^Meeting: SW336 Pioneering/}).click();
    await expect(page).toHaveURL(new RegExp(`/leader/weekly\\?meeting=${fixture.meetingId}$`));
    await page.getByRole("link", {name: "Back to calendar", exact: true}).click();
    await page.getByRole("button", {name: "Events", exact: true}).click();
    await expect(cell.getByRole("link", {name: /^Meeting:/})).toHaveCount(0);
    await page.getByRole("combobox", {name: "Calendar section"}).click();
    await page.getByRole("option", {name: "Scouts", exact: true}).click();
    await expect(grid.getByRole("link", {name: /SW336 Private audience/})).toHaveCount(0);
    await fixture.db.doc(`events/${fixture.eventId}`).update({title: "SW336 Camp updated"});
    await expect(cell.getByRole("link", {name: /^Event: SW336 Camp updated/})).toHaveCount(1);
    await cell.getByRole("link", {name: /^Event: SW336 Camp updated/}).click();
    await expect(page).toHaveURL(new RegExp(`/leader/events/${fixture.eventId}$`));
    await fixture.db.doc("siteSettings/calendarExperience").set({version: "existing"});
    await expect(page.getByRole("link", {name: "Back to calendar", exact: true})).toHaveCount(0);
    await fixture.db.doc("siteSettings/calendarExperience").set({version: "redesigned"});
    await expect(page.getByRole("link", {name: "Back to calendar", exact: true})).toBeVisible();
    await page.getByRole("link", {name: "Back to calendar", exact: true}).click();
    await expect(page).toHaveURL(new RegExp(`month=${fixture.month}.*type=event.*section=Scouts`));
    await page.reload();
    await expect(cell.getByRole("link", {name: /^Event: SW336 Camp updated/})).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({path: testInfo.outputPath("calendar-sources.png"), fullPage: true});
    await fixture.db.doc(`events/${fixture.eventId}`).delete();
    await expect(cell.getByRole("link", {name: /SW336 Camp updated/})).toHaveCount(0);
  } finally {await fixture.cleanup();}
});
test("parent sources use current child scope, safe details, expandable notes and revoke without retaining titles", async ({page}) => {
  test.skip(!password, "Configure canonical E2E credentials.");
  const fixture = await seedCalendarSources();
  const raw = new FirestoreListenTargets("events");
  page.on("request", request => {if (request.url().includes("/Listen/channel")) raw.record(request.postData());});
  try {
    await page.goto("/parent"); await page.getByLabel("Email", {exact: true}).fill(fixture.email); await page.getByLabel("Password", {exact: true}).fill(password!); await page.getByRole("button", {name: "Sign In", exact: true}).click();
    await expect(page.getByText(/Your account is approved and linked to 1 member record/)).toBeVisible();
    await page.goto(`/calendar?month=${fixture.month}`);
    const grid = page.getByRole("table", {name: "Monthly group calendar"});
    const cell = grid.locator(`[data-calendar-date="${fixture.month}-22"]`);
    await expect(cell.getByRole("link", {name: /^Meeting: SW336 Pioneering/})).toBeVisible();
    await expect(cell.getByRole("link", {name: /^Event: SW336 Camp/})).toBeVisible();
    await expect(grid.getByRole("link", {name: /SW336 Private audience/})).toHaveCount(0);
    // A selected snapshot audience grants this programme despite a different classification section.
    await expect(cell.getByRole("link", {name: /^Event: SW336 Selected camp/})).toBeVisible();
    await cell.getByRole("link", {name: /^Event: SW336 Selected camp/}).click();
    await expect(page.getByRole("heading", {name: "SW336 Selected camp", exact: true})).toBeVisible();
    const audience = fixture.db.doc("events/sw336-calendar-selected/audienceMembers/sw336-calendar-child");
    const original = (await audience.get()).data()!;
    await audience.delete();
    await expect(page.getByRole("heading", {name: "SW336 Selected camp", exact: true})).toHaveCount(0);
    await page.getByRole("link", {name: "Back to calendar", exact: true}).click();
    await expect(grid.getByRole("link", {name: /SW336 Selected camp/})).toHaveCount(0);
    const update = fixture.db.batch();
    update.update(fixture.db.doc("events/sw336-calendar-selected"), {startDate: `${fixture.month}-25`, endDate: `${fixture.month}-26`});
    update.update(fixture.db.doc("events/sw336-calendar-selected/programmes/parent"), {startDate: `${fixture.month}-25`, endDate: `${fixture.month}-26`});
    update.set(audience, {...original, startDate: `${fixture.month}-25`, endDate: `${fixture.month}-26`});
    await update.commit();
    await expect(cell.getByRole("link", {name: /SW336 Selected camp/})).toHaveCount(0);
    await expect(grid.locator(`[data-calendar-date="${fixture.month}-25"]`).getByRole("link", {name: /SW336 Selected camp/})).toHaveCount(1);
    await page.getByRole("combobox", {name: "Calendar section"}).click();
    await expect(page.getByRole("option", {name: "Beavers", exact: true})).toHaveCount(0); await page.getByRole("option", {name: "Scouts", exact: true}).click();
    await cell.getByRole("link", {name: /^Meeting: SW336 Pioneering/}).click();
    await expect(page.getByRole("heading", {name: "SW336 Pioneering", exact: true})).toBeVisible();
    await expect(page.getByText("Pioneering challenge · 20 minutes", {exact: true})).toBeVisible();
    await expect(page.getByText(/SW336 private/)).toHaveCount(0);
    await page.getByRole("link", {name: "Back to calendar", exact: true}).click();
    await cell.getByRole("link", {name: /^Event: SW336 Camp/}).click();
    await page.getByRole("button", {name: "Show more", exact: true}).click();
    await expect(page.getByText(/Final shared marker/)).toBeVisible();
    expect(raw.values()).toHaveLength(0);
    await fixture.db.doc("members/sw336-calendar-child").update({section: "Beavers", sections: ["Beavers"]});
    await expect(page.getByRole("heading", {name: "SW336 Camp", exact: true})).toHaveCount(0);
    await page.getByRole("link", {name: "Back to calendar", exact: true}).click();
    await expect(grid.getByRole("link", {name: /SW336 Camp|SW336 Pioneering/})).toHaveCount(0);
    await fixture.db.doc("members/sw336-calendar-child").update({section: "Scouts", sections: ["Scouts"]});
    await expect(cell.getByRole("link", {name: /^Event: SW336 Camp/})).toBeVisible();
    await cell.getByRole("link", {name: /^Event: SW336 Camp/}).click();
    await expect(page.getByRole("heading", {name: "SW336 Camp", exact: true})).toBeVisible();
    await fixture.db.doc(`parentAccounts/${fixture.uid}`).update({status: "revoked"});
    await expect(page.getByRole("heading", {name: "SW336 Camp", exact: true})).toHaveCount(0);
    await expect(page.getByText(/SW336 private/)).toHaveCount(0);
  } finally {await fixture.cleanup();}
});
