import {expect, test} from "@playwright/test";
import {getApps} from "firebase-admin/app";
import {getAuth} from "firebase-admin/auth";
import {scheduleFixtureDb} from "./support/schedule-fixtures";
import {loginAsLeader} from "./support/authentication-helpers";
import {scheduleToday} from "../src/services/scheduleSelection";
import {shiftCalendarMonth} from "../src/services/groupCalendar";
import {formatSiteDate} from "../src/services/siteDateFormat";
test("maintenance appointments validate, save, update, guard Back and obey independent rollout and membership", async ({page}, testInfo) => {
 test.setTimeout(45000);
 test.skip(!process.env.E2E_TEST_USER_PASSWORD, "Configure canonical E2E credentials.");
 const db=scheduleFixtureDb(), auth=getAuth(getApps().find(app=>app.name==="schedule-fixtures")!);
 const user=await auth.getUserByEmail(process.env.E2E_SUPER_ADMIN_EMAIL || "superadmin@example.com");
 const month=scheduleToday().slice(0,7), previous=shiftCalendarMonth(month,-1), next=shiftCalendarMonth(month,1), day=`${month}-22`;
 const base={title:"SW337 All day inspection",date:day,allDay:true,startTime:"",endTime:"",location:"Den",notes:"",revision:1,createdBy:user.uid,updatedBy:user.uid};
 const fixed="sw337-appointment-fixture-0001", outside="sw337-appointment-outside-0001";
 const paths=["siteSettings/calendarExperience","siteSettings/maintenanceExperience",`adminUsers/${user.uid}`,`maintenance/group/appointments/${fixed}`,`maintenance/group/appointments/${outside}`];
 const snapshots=await Promise.all(paths.map(path=>db.doc(path).get())); let createdId="";
 try {
  await db.doc(paths[0]).set({version:"redesigned"}); await db.doc(paths[1]).set({version:"redesigned",sdkRevision:1});
  await db.doc(paths[3]).set(base); await db.doc(paths[4]).set({...base,title:"SW337 Outside month",date:"2199-12-22"});
  await loginAsLeader(page,{email:user.email!,password:process.env.E2E_TEST_USER_PASSWORD!});
  await page.goto(`/calendar?month=${previous}&type=all`);
  await page.getByRole("link",{name:"Schedule maintenance",exact:true}).click();
  await expect(page.getByRole("heading",{name:"New service appointment"})).toBeVisible();
  await page.getByRole("button",{name:"Save appointment",exact:true}).click();
  await expect(page.getByRole("textbox",{name:/^Appointment title/})).toHaveAttribute("aria-invalid","true");
  await expect(page.getByRole("textbox",{name:/^Appointment title/})).toBeFocused();
  await page.getByRole("textbox",{name:/^Appointment title/}).fill("SW337 Boiler service");
  await page.getByRole("textbox",{name:/^Appointment date/}).fill("30-02-2026");
  await page.getByRole("button",{name:"Save appointment",exact:true}).click();
  await expect(page.getByRole("textbox",{name:/^Appointment date/})).toHaveAttribute("aria-invalid","true");
  await page.getByRole("textbox",{name:/^Appointment date/}).fill(formatSiteDate(day));
  await page.getByRole("checkbox",{name:"All day",exact:true}).uncheck();
  await page.getByLabel(/^Start time/).fill("08:30"); await page.getByLabel(/^End time/).fill("08:30");
  await page.getByRole("button",{name:"Save appointment",exact:true}).click();
  await expect(page.getByText("End time must be after start time.",{exact:true})).toBeVisible();
  await expect(page.getByLabel(/^End time/)).toBeFocused();
  await page.getByLabel(/^End time/).fill("09:30");
  await page.getByLabel("Location (optional)",{exact:true}).fill("Boiler room");
  await page.getByLabel("Notes (optional)",{exact:true}).fill("Service arrangements. ".repeat(100)+"Final service note marker.");
  await page.getByRole("button",{name:"Save appointment",exact:true}).click();
  await expect(page).toHaveURL(new RegExp(`month=${month}`));
  await expect(page.getByText("Maintenance appointment saved.",{exact:true})).toBeVisible();
  const grid=page.getByRole("table",{name:"Monthly group calendar"}), cell=grid.locator(`[data-calendar-date="${day}"]`);
  await expect(cell.getByRole("link",{name:/^Maintenance: SW337 Boiler service/})).toBeVisible();
  await expect(cell.getByRole("link",{name:/^Maintenance:/}).first()).toHaveAccessibleName(/SW337 All day inspection.*All day/);
  await expect(grid.getByRole("link",{name:/SW337 Outside month/})).toHaveCount(0);
  await cell.getByRole("link",{name:/^Maintenance: SW337 Boiler service/}).click();
  createdId=new URL(page.url()).pathname.split("/").at(-1)!;
  await expect(page.getByRole("heading",{name:"SW337 Boiler service",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Show more",exact:true}).click(); await expect(page.getByText(/Final service note marker/)).toBeVisible();
  await page.getByRole("link",{name:"Edit appointment",exact:true}).click();
  await expect(page.getByRole("alertdialog")).toHaveCount(0);
  await page.getByRole("textbox",{name:/^Appointment title/}).fill("Unwanted edit");
  await page.getByRole("link",{name:"Cancel",exact:true}).click();
  await expect(page.getByRole("alertdialog")).toBeVisible(); await page.getByRole("button",{name:"Stay",exact:true}).click();
  await expect(page.getByRole("textbox",{name:/^Appointment title/})).toHaveValue("Unwanted edit");
  await page.goBack(); await expect(page.getByRole("alertdialog")).toBeVisible(); await page.getByRole("button",{name:"Stay",exact:true}).click();
  await page.getByRole("link",{name:"Cancel",exact:true}).click(); await page.getByRole("button",{name:"Discard",exact:true}).click();
  await expect(cell.getByRole("link",{name:/^Maintenance: SW337 Boiler service/})).toBeVisible();
  await cell.getByRole("link",{name:/^Maintenance: SW337 Boiler service/}).click(); await page.getByRole("link",{name:"Edit appointment",exact:true}).click();
  await page.getByLabel("Location (optional)",{exact:true}).fill("Updated boiler room");
  await page.getByRole("link",{name:"Cancel",exact:true}).click(); await page.getByRole("alertdialog").getByRole("button",{name:"Save",exact:true}).click();
  await expect(page.getByText("Maintenance appointment saved.",{exact:true})).toBeVisible();
  await cell.getByRole("link",{name:/^Maintenance: SW337 Boiler service/}).click(); await page.getByRole("link",{name:"Edit appointment",exact:true}).click();
  await page.getByRole("textbox",{name:/^Appointment date/}).fill(formatSiteDate(`${next}-03`));
  await page.getByRole("checkbox",{name:"All day",exact:true}).check();
  await page.getByRole("button",{name:"Save appointment",exact:true}).click();
  await expect(page).toHaveURL(new RegExp(`month=${next}`));
  await expect(grid.locator(`[data-calendar-date="${next}-03"]`).getByRole("link",{name:/^Maintenance: SW337 Boiler service.*All day/})).toHaveCount(1);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:testInfo.outputPath("maintenance-appointment-calendar.png"),fullPage:true});
  await grid.getByRole("link",{name:/^Maintenance: SW337 Boiler service/}).click();
  await db.doc(paths[1]).set({version:"existing",sdkRevision:1});
  await expect(page.getByRole("heading",{name:"SW337 Boiler service",exact:true})).toHaveCount(0);
  await page.goto(`/calendar?month=${next}`); await expect(page.getByRole("link",{name:"Schedule maintenance",exact:true})).toHaveCount(0); await expect(grid.getByRole("link",{name:/SW337 Boiler service/})).toHaveCount(0);
  await db.doc(paths[1]).set({version:"redesigned",sdkRevision:1}); await expect(grid.getByRole("link",{name:/SW337 Boiler service/})).toBeVisible();
  await db.doc(paths[0]).set({version:"existing"}); await expect(page.getByTestId("page-group-calendar")).toHaveCount(0);
  expect((await db.doc(`maintenance/group/appointments/${createdId}`).get()).exists).toBe(true);
  await db.doc(paths[0]).set({version:"redesigned"}); await expect(grid.getByRole("link",{name:/SW337 Boiler service/})).toBeVisible();
  await grid.getByRole("link",{name:/SW337 Boiler service/}).click();
  await db.doc(paths[2]).update({active:false});
  await expect(page.getByRole("heading",{name:"SW337 Boiler service",exact:true})).toHaveCount(0);
 } finally {
  const partial=await db.collection("maintenance/group/appointments").where("title","==","SW337 Boiler service").limit(5).get();
  const batch=db.batch(); partial.docs.forEach(record=>batch.delete(record.ref)); snapshots.forEach(snapshot=>snapshot.exists?batch.set(snapshot.ref,snapshot.data()!):batch.delete(snapshot.ref)); if(createdId)batch.delete(db.doc(`maintenance/group/appointments/${createdId}`)); await batch.commit();
 }
});
