import { monitorCalendarActionReadiness, expectCalendarActionsReady } from "./support/calendar-action-readiness";
import {expect,test} from "@playwright/test";
import {getApps} from "firebase-admin/app";
import {getAuth} from "firebase-admin/auth";
import {scheduleFixtureDb} from "./support/schedule-fixtures";
import {loginAsLeader} from "./support/authentication-helpers";
import {scheduleToday} from "../src/services/scheduleSelection";
import {shiftCalendarMonth} from "../src/services/groupCalendar";
import {formatSiteDate} from "../src/services/siteDateFormat";
test("an existing task has one live schedule, opens its canonical workflow and retains Calendar context",async({page},testInfo)=>{
 test.setTimeout(45000); test.skip(!process.env.E2E_TEST_USER_PASSWORD,"Configure canonical E2E credentials.");
 const db=scheduleFixtureDb(), auth=getAuth(getApps().find(app=>app.name==="schedule-fixtures")!);
 const user=await auth.getUserByEmail(process.env.E2E_SUPER_ADMIN_EMAIL||"superadmin@example.com");
 const taskId="sw338-task-calendar-source-001", appointmentId=`task-${taskId}`, month=scheduleToday().slice(0,7), next=shiftCalendarMonth(month,1);
 const paths=["siteSettings/calendarExperience","siteSettings/maintenanceExperience",`adminUsers/${user.uid}`,`maintenance/group/tasks/${taskId}`,`maintenance/group/appointments/${appointmentId}`];
 const originals=await Promise.all(paths.map(path=>db.doc(path).get()));
 try{
  await db.doc(paths[0]).set({version:"redesigned"}); await db.doc(paths[1]).set({version:"redesigned",sdkRevision:1});
  await db.doc(paths[3]).set({description:"SW338 Repair the entrance door\nKeep the canonical instructions and documents here.",documentIds:[],status:"open",assigneeUid:user.uid,assigneeName:"Original responsible leader",assignmentMode:"explicit",revision:1,createdAt:Date.now(),createdBy:user.uid,updatedBy:user.uid});
  await db.doc(paths[4]).delete();
  await monitorCalendarActionReadiness(page);
  await loginAsLeader(page,{email:user.email!,password:process.env.E2E_TEST_USER_PASSWORD!});
  await page.goto(`/calendar?month=${month}&type=maintenance`);
  await expectCalendarActionsReady(page);
  await page.getByRole("link",{name:"Schedule maintenance task",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Choose maintenance task",exact:true})).toBeVisible();
  await page.getByRole("link",{name:/Schedule task: SW338 Repair the entrance door/}).click();
  await expect(page.getByText("Responsible leader: Original responsible leader · Open",{exact:true})).toBeVisible();
  await expect(page.getByRole("textbox",{name:/Appointment title/})).toHaveCount(0);
  await page.getByRole("textbox",{name:/^Appointment date/}).fill(formatSiteDate(`${month}-22`));
  await page.getByRole("checkbox",{name:"All day",exact:true}).uncheck();
  await page.getByLabel(/^Start time/).fill("10:00"); await page.getByLabel(/^End time/).fill("11:00");
  await page.getByLabel("Notes (optional)",{exact:true}).fill("Scheduling arrangements only.");
  await page.getByRole("button",{name:"Save appointment",exact:true}).click();
  await expect(page).toHaveURL(new RegExp(`month=${month}.*type=maintenance`));
  const grid=page.getByRole("table",{name:"Monthly group calendar"}), cell=grid.locator(`[data-calendar-date="${month}-22"]`);
  await expect(cell.getByRole("link",{name:/^Maintenance: SW338 Repair the entrance door.*10:00.*Original responsible leader.*Open/})).toHaveCount(1);
  const saved=(await db.doc(paths[4]).get()).data()!;
  expect(saved.taskId).toBe(taskId); expect(saved.title).toBe(""); expect(saved.assigneeName).toBeUndefined(); expect(saved.status).toBeUndefined(); expect(saved.description).toBeUndefined();
  await db.doc(paths[3]).update({description:"SW338 Door repaired",assigneeName:"New responsible leader",status:"complete",revision:2});
  await expect(cell.getByRole("link",{name:/^Maintenance: SW338 Door repaired.*New responsible leader.*Complete/})).toHaveCount(1);
  await expect(grid.getByRole("link",{name:/Original responsible leader/})).toHaveCount(0);
  await cell.getByRole("link",{name:/^Maintenance: SW338 Door repaired/}).click();
  await expect(page).toHaveURL(new RegExp(`/maintenance/tasks/${taskId}$`));
  await expect(page.getByRole("heading",{name:"Task details",exact:true})).toBeVisible();
  await expect(page.getByText("Responsible leader: New responsible leader",{exact:true})).toBeVisible();
  await expect(page.getByText("No linked documents.",{exact:true})).toBeVisible();
  await page.getByRole("link",{name:"Reschedule task",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Reschedule task",exact:true})).toBeVisible();
  await page.getByRole("textbox",{name:/^Appointment date/}).fill(formatSiteDate(`${next}-03`));
  await page.getByRole("checkbox",{name:"All day",exact:true}).check(); await page.getByRole("button",{name:"Save appointment",exact:true}).click();
  await expect(page).toHaveURL(new RegExp(`month=${next}.*type=maintenance`));
  await expect(grid.locator(`[data-calendar-date="${next}-03"]`).getByRole("link",{name:/^Maintenance: SW338 Door repaired.*All day/})).toHaveCount(1);
  expect((await db.collection("maintenance/group/appointments").where("taskId","==",taskId).get()).size).toBe(1);
  await page.getByRole("button",{name:"Previous month",exact:true}).click();
  await expect(cell.getByRole("link",{name:/^Maintenance: SW338 Door repaired/})).toHaveCount(0);
  await page.getByRole("button",{name:"Next month",exact:true}).click();
  await grid.getByRole("link",{name:/^Maintenance: SW338 Door repaired/}).click();
  await page.getByRole("link",{name:"Back to calendar",exact:true}).click();
  await expect(page).toHaveURL(new RegExp(`month=${next}.*type=maintenance`));
  await page.screenshot({path:testInfo.outputPath("scheduled-task-calendar.png"),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await grid.getByRole("link",{name:/^Maintenance: SW338 Door repaired/}).click();
  const currentTask=(await db.doc(paths[3]).get()).data()!; await db.doc(paths[3]).delete();
  await expect(page.getByText("SW338 Door repaired",{exact:true})).toHaveCount(0);
  await expect(page.getByText(/This task is unavailable/)).toBeVisible();
  await page.getByRole("link",{name:"Back to calendar",exact:true}).click();
  await expect(grid.getByRole("link",{name:/^Maintenance: Maintenance task unavailable/})).toBeVisible();
  await expect(grid.getByRole("link",{name:/SW338 Door repaired/})).toHaveCount(0);
  await db.doc(paths[3]).set(currentTask); await expect(grid.getByRole("link",{name:/SW338 Door repaired/})).toBeVisible();
  await grid.getByRole("link",{name:/SW338 Door repaired/}).click();
  await db.doc(paths[1]).set({version:"existing",sdkRevision:1});
  await expect(page.getByText("SW338 Door repaired",{exact:true})).toHaveCount(0);
  await page.goto(`/calendar?month=${next}&type=maintenance`); await expect(grid.getByRole("link",{name:/SW338 Door repaired/})).toHaveCount(0);
  await db.doc(paths[1]).set({version:"redesigned",sdkRevision:1}); await expect(grid.getByRole("link",{name:/SW338 Door repaired/})).toBeVisible();
  await grid.getByRole("link",{name:/SW338 Door repaired/}).click();
  await db.doc(paths[2]).update({active:false});
  await expect(page.getByText("SW338 Door repaired",{exact:true})).toHaveCount(0);
  expect((await db.doc(paths[3]).get()).data()!.status).toBe("complete"); expect((await db.doc(paths[4]).get()).exists).toBe(true);
 }finally{const batch=db.batch(); originals.forEach(snapshot=>snapshot.exists?batch.set(snapshot.ref,snapshot.data()!):batch.delete(snapshot.ref)); await batch.commit();}
});
