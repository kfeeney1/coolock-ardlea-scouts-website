import { expect, test, type Page } from "@playwright/test";
import { loginAsLeader } from "./support/authentication-helpers";
import { scheduleFixtureDb } from "./support/schedule-fixtures";
import { waitForTransientOverlayHistory } from "./helpers/transientOverlayHistory";
import { reconcileOpenWeeklyRoster } from "../src/services/weeklyTrackerLogic";
const password = process.env.E2E_TEST_USER_PASSWORD;
const id = "000-sw420-compact-plan";
const libraryId = "000-sw420-library";
const activity = (key: string, name: string, duration: number) => ({ id: key, activity: name, leader: "All leaders", equipment: "Cones", notes: "Existing instructions", durationMinutes: duration });
async function enter(page: Page) {
  await loginAsLeader(page, { email: process.env.E2E_SUPER_ADMIN_EMAIL || "superadmin@example.com", password: password! });
  await page.goto(`/leader/weekly?meeting=${id}`);
  await expect(page.getByRole("button", { name: "Plan", exact: true })).toHaveAttribute("aria-pressed", "true");
}
test.beforeEach(async () => {
  test.skip(!password, "Configure canonical E2E credentials.");
  const db = scheduleFixtureDb();
  await db.doc("siteSettings/meetingExperience").set({ version: "redesigned" });
  const members = (await db.collection("members").get()).docs.map(doc => ({ id: doc.id, ...doc.data() }));
  await db.doc(`weeklyMeetings/${id}`).set({ section: "Scouts", meetingDate: "2099-07-22", status: "open", location: "Synthetic den", programmeNotes: JSON.stringify({ marker: "weekly-programme-v1", theme: "Compact programme fixture", notes: "Fixture programme notes" }), plannedActivities: JSON.stringify({ marker: "weekly-activities-v1", items: [activity("one", "River banks", 20), activity("two", "Team challenge", 15)] }), plannedBadgework: JSON.stringify({ marker: "weekly-badgework-v1", items: [{ id: "skill", badge: "Pioneering", leader: "All leaders", equipment: "Rope", notes: "Existing badge notes", durationMinutes: 10 }] }), entries: reconcileOpenWeeklyRoster([], members as Parameters<typeof reconcileOpenWeeklyRoster>[1], "Scouts"), injuries: [], notes: "", testData: true });
  await db.doc(`programmeLibrary/${libraryId}`).set({ section: "Scouts", kind: "activity", name: "SW420 reusable challenge", leader: "Guest leader", equipment: "Bibs", notes: "Reusable instructions", durationMinutes: 25 });
});
test.afterEach(async () => {
  const db = scheduleFixtureDb();
  for (const path of [`weeklyMeetings/${id}`, `parentWeeklyMeetings/${id}`, `programmeLibrary/${libraryId}`, "siteSettings/meetingExperience"]) await db.doc(path).delete();
});

test("Compact activity editors preserve leaders, guests, equipment, durations and instructions across stages and reload", async ({ page }, testInfo) => {
  await enter(page);
  if (testInfo.project.name === "mobile-chromium") await page.setViewportSize({ width: 320, height: 800 });
  const first = page.getByTestId("activity-plan-row").first();
  const expand = page.getByRole("button", { name: /^Activity 1: River banks/ });
  await expect(expand).toHaveAttribute("aria-expanded", "false");
  await expect(first.getByRole("textbox", { name: "Activity 1", exact: true })).toBeHidden();
  await expand.focus(); await page.keyboard.press("Enter");
  await expect(expand).toHaveAttribute("aria-expanded", "true");
  const title = "River banks with long programme content that must wrap without clipping on a narrow Android screen";
  await first.getByRole("textbox", { name: "Activity 1", exact: true }).fill(title);
  await first.getByRole("textbox", { name: "Equipment 1", exact: true }).fill("Bibs, cones and a long equipment description");
  await first.getByRole("spinbutton", { name: "Activity duration (minutes) 1", exact: true }).fill("100");
  await first.getByRole("textbox", { name: "Instructions / notes 1", exact: true }).fill("Full activity instructions\nPreserve this second line");
  await first.getByRole("checkbox", { name: "All leaders", exact: true }).uncheck();
  const selected = first.getByRole("checkbox").nth(1); const selectedName = (await selected.evaluate(input => input.closest("label")?.textContent || "")).split(" · ")[0].trim();
  await selected.check();
  await first.getByRole("textbox", { name: "Other leader(s)", exact: true }).fill("Guest One | Guest Two");
  await expect(page.getByTestId("programme-duration-total")).toContainText("125 minutes");
  await expect(page.getByTestId("programme-duration-warning")).toContainText("35 minutes longer");
  await page.getByRole("button", { name: "Run", exact: true }).click();
  await page.getByRole("button", { name: "Plan", exact: true }).click();
  await expect(first.getByRole("textbox", { name: "Other leader(s)", exact: true })).toHaveValue("Guest One | Guest Two");
  await expect(selected).toBeChecked();
  await page.getByRole("textbox", { name: "Theme", exact: true }).fill("Updated programme fixture");
  await page.getByRole("textbox", { name: "Location", exact: true }).fill("New synthetic den");
  await page.getByRole("textbox", { name: "Programme notes", exact: true }).fill("Updated notes kept separately from activity instructions");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole("button", { name: "Save Meeting", exact: true }).click();
  await expect(page.getByTestId("meeting-save-state")).toHaveText("Saved");
  await page.reload();
  await page.getByRole("button", { name: /^Activity 1: River banks/ }).click();
  await expect(first.getByRole("textbox", { name: "Activity 1", exact: true })).toHaveValue(title);
  await expect(first.getByRole("textbox", { name: "Other leader(s)", exact: true })).toHaveValue("Guest One | Guest Two");
  await expect(first.getByRole("textbox", { name: "Instructions / notes 1", exact: true })).toHaveValue("Full activity instructions\nPreserve this second line");
  const stored = (await scheduleFixtureDb().doc(`weeklyMeetings/${id}`).get()).data()!;
  const row = JSON.parse(stored.plannedActivities).items[0];
  expect(row.durationMinutes).toBe(100); expect(row.leader).toContain("Guest One"); expect(row.leader).toContain("Guest Two"); expect(row.leader).not.toBe("Guest One | Guest Two");
  expect(JSON.parse(stored.plannedBadgework).items[0].badge).toBe("Pioneering");
  expect(row.leader).toContain(selectedName);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath("compact-plan.png"), fullPage: true });
});

test("Zero, new and library-inserted items retain distinct identities and equipment planning remains accessible", async ({ page }) => {
  const ref = scheduleFixtureDb().doc(`weeklyMeetings/${id}`);
  await ref.update({ plannedActivities: JSON.stringify({ marker: "weekly-activities-v1", items: [] }), plannedBadgework: JSON.stringify({ marker: "weekly-badgework-v1", items: [] }) });
  await enter(page);
  await expect(page.getByText("No activities planned yet.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Add activity / game", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Activity 1", exact: true })).toBeVisible();
  await page.getByRole("textbox", { name: "Activity 1", exact: true }).fill("A new game");
  await page.getByRole("button", { name: "Programme library", exact: true }).click();
  const library = page.getByTestId("programme-library-panel");
  await library.getByRole("combobox", { name: "Saved programme item", exact: true }).click();
  await page.getByRole("option", { name: /SW420 reusable challenge/ }).click();
  await expect(library.getByRole("combobox", { name: "Saved programme item", exact: true })).toContainText("SW420 reusable challenge");
  await waitForTransientOverlayHistory(page);
  await library.getByRole("button", { name: "Add to meeting", exact: true }).click();
  await expect(page.getByTestId("activity-plan-row")).toHaveCount(2);
  await page.getByRole("button", { name: /^Activity 2: SW420 reusable challenge/ }).click();
  await expect(page.getByRole("textbox", { name: "Equipment 2", exact: true })).toHaveValue("Bibs");
  await page.getByRole("button", { name: "Add badgework", exact: true }).click();
  await page.getByRole("textbox", { name: "Badgework 1", exact: true }).fill("New badgework");
  await page.getByRole("textbox", { name: "Badgework instructions / notes 1", exact: true }).fill("Separate badgework instructions");
  await page.getByTestId("weekly-programme-equipment-button").click();
  await expect(page.getByRole("dialog")).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("button", { name: "Save Meeting", exact: true }).click();
  await expect(page.getByTestId("meeting-save-state")).toHaveText("Saved");
  const stored = (await ref.get()).data()!;
  const rows = JSON.parse(stored.plannedActivities).items;
  expect(rows).toHaveLength(2); expect(new Set(rows.map((row: { id: string }) => row.id)).size).toBe(2);
  expect(JSON.parse(stored.plannedBadgework).items[0].notes).toBe("Separate badgework instructions");
});

test("Legacy planning stays expanded and closed redesigned planning retains locks", async ({ page }) => {
  const db = scheduleFixtureDb();
  await db.doc("siteSettings/meetingExperience").set({ version: "existing" });
  await loginAsLeader(page, { email: process.env.E2E_SUPER_ADMIN_EMAIL || "superadmin@example.com", password: password! });
  await page.goto(`/leader/weekly?meeting=${id}`);
  await page.getByRole("button", { name: "Programme", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Activity 1", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: /^Activity 1: River banks/ })).toHaveCount(0);
  await db.doc(`weeklyMeetings/${id}`).update({ status: "closed" });
  await db.doc("siteSettings/meetingExperience").set({ version: "redesigned" });
  await page.reload();
  await page.getByRole("button", { name: "Plan", exact: true }).click();
  await page.getByRole("button", { name: /^Activity 1: River banks/ }).click();
  await expect(page.getByRole("textbox", { name: "Activity 1", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: /^Badgework 1: Pioneering/ }).click();
  await expect(page.getByRole("textbox", { name: "Badgework 1", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Add activity / game", exact: true })).toHaveCount(0);
});
